import jsPDF from 'jspdf';

export function generateComplianceReport(mine, reports, checklist) {
  try {
    const doc = new jsPDF('p', 'mm', 'a4');
    const pageW = doc.internal.pageSize.getWidth();
    const margin = 14;
    let y = 20;

    // Helper: add text and advance y
    const addText = (text, size, color, bold = false) => {
      doc.setFontSize(size);
      doc.setTextColor(...color);
      if (bold) doc.setFont('helvetica', 'bold');
      else doc.setFont('helvetica', 'normal');
      doc.text(text, margin, y);
      y += size * 0.5;
    };

    const addLine = () => {
      doc.setDrawColor(44, 62, 80);
      doc.setLineWidth(0.5);
      doc.line(margin, y, pageW - margin, y);
      y += 4;
    };

    let xOff = margin;

    const checkPage = (needed) => {
      if (y + needed > doc.internal.pageSize.getHeight() - 20) {
        doc.addPage();
        y = 20;
      }
    };

    // === HEADER ===
    addText('Coal India Limited', 18, [44, 62, 80], true);
    y += 2;
    addText('Compliance Report', 14, [44, 62, 80], true);
    y += 4;
    addLine();

    addText(`Mine: ${mine.name}`, 11, [80], true);
    addText(`Subsidiary: ${mine.subsidiary}  |  State: ${mine.state}  |  Type: ${mine.type}`, 10, [100]);
    addText(`Report Date: ${new Date().toLocaleDateString('en-IN')}`, 10, [100]);
    addText('Generated by: AI-Based Smart Governance Platform (SIH 2026)', 9, [140]);
    y += 6;

    // === SUMMARY ===
    addText('Summary', 12, [44, 62, 80], true);
    y += 2;

    const mineReports = reports.filter(r => r.mineId === mine.id);
    const openCount = mineReports.filter(r => r.status === 'Open').length;
    const inProgressCount = mineReports.filter(r => r.status === 'In Progress').length;
    const resolvedCount = mineReports.filter(r => r.status === 'Resolved').length;
    const escalatedCount = mineReports.filter(r => r.escalated).length;

    const mineChecklist = checklist.filter(c => c.mineId === mine.id);
    const compliant = mineChecklist.filter(c => c.status === 'Compliant').length;
    const compliancePct = mineChecklist.length > 0 ? Math.round((compliant / mineChecklist.length) * 100) : 0;

    // Summary table
    const summaryRows = [
      ['Total Reports', String(mineReports.length)],
      ['Open Violations', String(openCount)],
      ['In Progress', String(inProgressCount)],
      ['Resolved', String(resolvedCount)],
      ['Escalated', String(escalatedCount)],
      ['Compliance Score', `${compliancePct}%`],
    ];

    // Draw summary table
    const col1W = 60;
    const col2W = 40;
    const tableW = col1W + col2W;
    const startX = margin;

    // Header row
    doc.setFillColor(44, 62, 80);
    doc.rect(startX, y, tableW, 8, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(255);
    doc.text('Metric', startX + 3, y + 5.5);
    doc.text('Value', startX + col1W + 3, y + 5.5);
    y += 8;

    // Data rows
    summaryRows.forEach((row, i) => {
      const bgColor = i % 2 === 0 ? [245, 245, 245] : [255, 255, 255];
      doc.setFillColor(...bgColor);
      doc.rect(startX, y, tableW, 7, 'F');
      doc.setDrawColor(220, 220, 220);
      doc.rect(startX, y, tableW, 7, 'S');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(60);
      doc.text(row[0], startX + 3, y + 5);
      doc.setFont('helvetica', 'normal');
      doc.text(row[1], startX + col1W + 3, y + 5);
      y += 7;
    });
    y += 8;

    // === VIOLATIONS TABLE ===
    checkPage(30);
    addText('Open & In-Progress Violations', 12, [44, 62, 80], true);
    y += 2;

    const violations = mineReports.filter(r => r.status !== 'Resolved').slice(0, 50);

    if (violations.length > 0) {
      const vCols = [14, 30, 55, 18, 16, 22, 22]; // widths
      const vHeaders = ['ID', 'Category', 'Description', 'Status', 'Priority', 'Contractor', 'Date'];

      // Header
      doc.setFillColor(44, 62, 80);
      doc.rect(startX, y, pageW - 2 * margin, 7, 'F');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(7);
      doc.setTextColor(255);
      xOff = startX + 2;
      vHeaders.forEach((h, i) => {
        doc.text(h, xOff, y + 5);
        xOff += vCols[i];
      });
      y += 7;

      // Rows
      violations.forEach((r, i) => {
        checkPage(8);
        const bgColor = i % 2 === 0 ? [250, 250, 250] : [255, 255, 255];
        doc.setFillColor(...bgColor);
        doc.rect(startX, y, pageW - 2 * margin, 6, 'F');
        doc.setDrawColor(230, 230, 230);
        doc.rect(startX, y, pageW - 2 * margin, 6, 'S');

        doc.setFont('helvetica', 'normal');
        doc.setFontSize(6.5);
        xOff = startX + 2;

        const rowData = [
          r.id,
          r.category.substring(0, 22),
          r.description.substring(0, 40),
          r.status,
          r.priority,
          (r.contractor || 'N/A').substring(0, 18),
          r.date,
        ];

        rowData.forEach((cell, ci) => {
          if (ci === 3) {
            // Status color
            if (cell === 'Open') doc.setTextColor(220, 53, 69);
            else if (cell === 'In Progress') doc.setTextColor(200, 120, 0);
            else doc.setTextColor(40, 167, 69);
            doc.setFont('helvetica', 'bold');
          } else {
            doc.setTextColor(60);
            doc.setFont('helvetica', 'normal');
          }
          doc.text(String(cell).substring(0, vCols[ci] / 1.8), xOff, y + 4.5);
          xOff += vCols[ci];
        });
        y += 6;
      });
    } else {
      addText('No open or in-progress violations.', 10, [100]);
    }
    y += 8;

    // === COMPLIANCE CHECKLIST ===
    checkPage(30);
    addText('Compliance Checklist Summary', 12, [44, 62, 80], true);
    y += 2;

    const categories = [...new Set(mineChecklist.map(c => c.category))];
    if (categories.length > 0) {
      const cCols = [55, 18, 22, 28, 18];
      const cHeaders = ['Category', 'Total', 'Compliant', 'Non-Compliant', 'Pending'];

      // Header
      doc.setFillColor(44, 62, 80);
      doc.rect(startX, y, pageW - 2 * margin, 7, 'F');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(255);
      xOff = startX + 2;
      cHeaders.forEach((h, i) => {
        doc.text(h, xOff, y + 5);
        xOff += cCols[i];
      });
      y += 7;

      categories.forEach((cat, i) => {
        checkPage(8);
        const items = mineChecklist.filter(c => c.category === cat);
        const comp = items.filter(c => c.status === 'Compliant').length;
        const nonComp = items.filter(c => c.status === 'Non-Compliant').length;
        const pend = items.filter(c => c.status === 'Pending').length;

        const bgColor = i % 2 === 0 ? [250, 250, 250] : [255, 255, 255];
        doc.setFillColor(...bgColor);
        doc.rect(startX, y, pageW - 2 * margin, 6, 'F');
        doc.setDrawColor(230, 230, 230);
        doc.rect(startX, y, pageW - 2 * margin, 6, 'S');

        doc.setFont('helvetica', 'normal');
        doc.setFontSize(7.5);
        doc.setTextColor(60);
        xOff = startX + 2;
        [cat, String(items.length), String(comp), String(nonComp), String(pend)].forEach((cell, ci) => {
          doc.text(String(cell).substring(0, 30), xOff, y + 4.5);
          xOff += cCols[ci];
        });
        y += 6;
      });
    }

    // === FOOTER ===
    const pageCount = doc.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);
      doc.setFontSize(7);
      doc.setTextColor(150);
      doc.text(
        `Page ${i} of ${pageCount} | AI-Based Smart Governance Platform — SIH 2026 | Confidential`,
        margin, doc.internal.pageSize.getHeight() - 8
      );
    }

    // Save
    const filename = `${mine.name.replace(/[^a-zA-Z0-9]/g, '_')}_Compliance_Report_${new Date().toISOString().split('T')[0]}.pdf`;
    doc.save(filename);
    return true;
  } catch (err) {
    console.error('PDF generation error:', err);
    alert('PDF generation failed: ' + err.message);
    return false;
  }
}
